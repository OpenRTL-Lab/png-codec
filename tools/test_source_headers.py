"""Header-only transform identity, idempotency, corruption and inventory controls."""
import shutil
import tempfile
from pathlib import Path
from source_headers import add, strip
from check_publication import ROOT, check


def main():
    for name, body in [('x.py', b'#!/usr/bin/env python3\nprint(1)\n'),
                       ('build.mill', b'//| mill-version: 1.1.7\npackage build\n'),
                       ('x.sv', b'// Generated by CIRCT firtool-1.149.0\nmodule x; endmodule\n'),
                       ('x.md', b'# Example\n')]:
        published = add(name, body)
        assert strip(name, published) == body
        assert add(name, published) == published
        for bad in (body, published + b'// OpenRTL file declaration\n',
                    published.replace(b'OpenRTL Lab', b'Changed Lab', 1)):
            try:
                strip(name, bad)
            except ValueError:
                pass
            else:
                raise AssertionError('HEADER_CONTROL_NOT_REJECTED')
    with tempfile.TemporaryDirectory(prefix='png-header-control-') as temp:
        copy = Path(temp) / 'source'
        shutil.copytree(ROOT, copy, ignore=shutil.ignore_patterns('.git', 'out', 'build', 'dependencies', '__pycache__'))
        check(copy)
        target = copy / 'rtl/encode/rtl/PngEncoder.sv'
        original = target.read_bytes()
        target.write_bytes(original + b'// altered body\n')
        try:
            check(copy)
        except AssertionError as e:
            assert 'BODY_SHA' in str(e)
        else:
            raise AssertionError('BODY_CONTROL_NOT_REJECTED')
        target.write_bytes(original)
        (copy / 'unexpected.txt').write_text('unexpected\n')
        try:
            check(copy)
        except AssertionError as e:
            assert 'INVENTORY' in str(e)
        else:
            raise AssertionError('INVENTORY_CONTROL_NOT_REJECTED')
    print('PNG_PUBLIC_HEADERS_PASS: exact-body/idempotency/missing/duplicate/tamper/inventory')


if __name__ == '__main__':
    main()
